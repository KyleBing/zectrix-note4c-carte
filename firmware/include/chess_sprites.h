struct ChessSpr { const uint16_t *rows; int h; };
static ChessSpr chessSprite(int piece /*1=K..6=P*/, bool white) {
  // Piece enum: K=1 Q=2 R=3 B=4 N=5 P=6
  static const ChessSpr blk[] = {
    {nullptr,0},
    {kChessBK, kChessBKH}, {kChessBQ, kChessBQH}, {kChessBR, kChessBRH},
    {kChessBB, kChessBBH}, {kChessBN, kChessBNH}, {kChessBP, kChessBPH},
  };
  static const ChessSpr wht[] = {
    {nullptr,0},
    {kChessWK, kChessWKH}, {kChessWQ, kChessWQH}, {kChessWR, kChessWRH},
    {kChessWB, kChessWBH}, {kChessWN, kChessWNH}, {kChessWP, kChessWPH},
  };
  if (piece < 1 || piece > 6) return {nullptr,0};
  return white ? wht[piece] : blk[piece];
}

