#!/usr/bin/env python3
"""Convert design/{piece}.png / {piece}_black.png → firmware/include/chess_sprites.h.

Only black/white pixels: gray fill uses checkerboard dither (x+y)&1.
Transparent stays transparent (mask bit clear).

Prefer @2x sources when resizing (sharper downsample).
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DESIGN = ROOT / "design"
OUT = ROOT / "firmware" / "include" / "chess_sprites.h"

# 带行列标注时格子约 32，棋子略小留白
SIZE = 28
BPR = (SIZE + 7) // 8

# (slug, Piece letter for ident)
PIECES = [
    ("king", "K"),
    ("queen", "Q"),
    ("rook", "R"),
    ("bishop", "B"),
    ("knight", "N"),
    ("pawn", "P"),
]


def classify(r: int, g: int, b: int, a: int, x: int, y: int) -> int | None:
    """None=transparent, 0=white, 1=black."""
    if a < 40:
        return None
    luma = 0.299 * r + 0.587 * g + 0.114 * b
    if luma < 80:
        return 1
    if luma > 220:
        return 0
    # 灰：黑白相间
    return 1 if ((x + y) & 1) else 0


def load_piece(path_1x: Path) -> Image.Image:
    # 缩小优先用 @2x，再 Lanczos 到目标尺寸后量化
    stem = path_1x.stem  # e.g. king / king_black
    path_2x = path_1x.with_name(f"{stem}@2x.png")
    src = path_2x if path_2x.exists() else path_1x
    im = Image.open(src).convert("RGBA")
    if im.size != (SIZE, SIZE):
        im = im.resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    return im


def pack_planes(im: Image.Image) -> tuple[list[int], list[int]]:
    mask = [0] * (SIZE * BPR)
    ink = [0] * (SIZE * BPR)
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b, a = im.getpixel((x, y))
            c = classify(r, g, b, a, x, y)
            if c is None:
                continue
            bi = y * BPR + (x >> 3)
            bit = 1 << (7 - (x & 7))
            mask[bi] |= bit
            if c == 1:
                ink[bi] |= bit
    return mask, ink


def c_array(name: str, data: list[int], per: int = 12) -> str:
    lines = [f"static const uint8_t {name}[] PROGMEM = {{"]
    for i in range(0, len(data), per):
        chunk = ", ".join(f"0x{b:02X}" for b in data[i : i + per])
        lines.append(f"  {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    parts: list[str] = [
        "// Generated by tools/rasterize_chess.py — do not edit by hand.",
        "// Source: design/{king,queen,rook,bishop,knight,pawn}[_black][@2x].png",
        "// Gray → checkerboard dither; only black/white ink.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        f"static constexpr int kChessSprW = {SIZE};",
        f"static constexpr int kChessSprH = {SIZE};",
        f"static constexpr int kChessSprBpr = {BPR};",
        "",
        "struct ChessSpr {",
        "  const uint8_t *mask;  // opaque",
        "  const uint8_t *ink;   // black where set; white where clear (if masked)",
        "  int w;",
        "  int h;",
        "};",
        "",
    ]

    for slug, letter in PIECES:
        for black in (False, True):
            fname = f"{slug}_black.png" if black else f"{slug}.png"
            path = DESIGN / fname
            if not path.exists():
                raise SystemExit(f"missing {path}")
            mask, ink = pack_planes(load_piece(path))
            side = "B" if black else "W"
            base = f"kChess{side}{letter}"
            parts.append(c_array(f"{base}_m", mask))
            parts.append("")
            parts.append(c_array(f"{base}_i", ink))
            parts.append("")

    parts.append("static ChessSpr chessSprite(int piece /*1=K..6=P*/, bool white) {")
    parts.append("  // Piece enum: K=1 Q=2 R=3 B=4 N=5 P=6")
    parts.append("  static const ChessSpr blk[] = {")
    parts.append("    {nullptr, nullptr, 0, 0},")
    for slug, letter in PIECES:
        parts.append(
            f"    {{kChessB{letter}_m, kChessB{letter}_i, kChessSprW, kChessSprH}},"
        )
    parts.append("  };")
    parts.append("  static const ChessSpr wht[] = {")
    parts.append("    {nullptr, nullptr, 0, 0},")
    for slug, letter in PIECES:
        parts.append(
            f"    {{kChessW{letter}_m, kChessW{letter}_i, kChessSprW, kChessSprH}},"
        )
    parts.append("  };")
    parts.append("  if (piece < 1 || piece > 6) return {nullptr, nullptr, 0, 0};")
    parts.append("  return white ? wht[piece] : blk[piece];")
    parts.append("}")
    parts.append("")

    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes) size={SIZE}")


if __name__ == "__main__":
    main()
